-- 1. Enable UUID extension
create extension if not exists "uuid-ossp";

-- 2. Users Table (Base essentielle)
create table public.users (
  id bigint generated by default as identity primary key,
  auth_id uuid references auth.users(id), -- Lien vers Supabase Auth
  email text,
  child_username text,
  password_hash text, -- Peut être null car géré par Supabase Auth
  first_name text,
  last_name text,
  role text not null check (role in ('admin', 'parent', 'child')),
  parent_id bigint references public.users(id),
  grade_level text,
  avatar text default 'default.png',
  status text not null default 'pending_verification' check (status in ('pending_verification', 'active', 'inactive', 'banned')),
  created_at timestamp with time zone default timezone('utc'::text, now()),
  updated_at timestamp with time zone default timezone('utc'::text, now()),
  
  -- Champs simplifiés pour le futur (optionnels pour l'instant mais pratiques)
  account_type text default 'parent' check (account_type in ('parent', 'child', 'autonomous_child')),
  subscription_plan_id bigint,
  subscription_expires_at timestamp with time zone
);

-- 3. Sécurité (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- Politique : Chacun voit son propre profil
CREATE POLICY "Users can view their own profile" 
ON public.users FOR SELECT 
USING (auth.uid() = auth_id);

-- Politique : Chacun modifie son propre profil
CREATE POLICY "Users can update their own profile" 
ON public.users FOR UPDATE 
USING (auth.uid() = auth_id);

-- Politique : Création de compte (Inscription)
CREATE POLICY "Enable insert for authentication" 
ON public.users FOR INSERT 
WITH CHECK (auth.uid() = auth_id);

-- Politique : Les Parents voient leurs enfants
-- (Les enfants ont 'parent_id' qui pointe vers l'ID du parent)
CREATE POLICY "Parents can view their children" 
ON public.users FOR SELECT 
USING (
  parent_id IN (
    SELECT id FROM public.users WHERE auth_id = auth.uid()
  )
);
