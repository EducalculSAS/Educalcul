-- Update Exercises Table for AI and Open-Ended Problems
ALTER TABLE public.exercises 
ADD COLUMN IF NOT EXISTS grading_type text DEFAULT 'auto', -- 'auto', 'ai', 'manual'
ADD COLUMN IF NOT EXISTS ai_generated boolean DEFAULT false,
ADD COLUMN IF NOT EXISTS grading_rubric jsonb, -- { "criteria": ["..."], "max_points": 10 }
ADD COLUMN IF NOT EXISTS solution_text text, -- Full solution path for reference
ADD COLUMN IF NOT EXISTS user_prompt text; -- The prompt user used to generate this (if AI)

-- Ensure content_json is consistent
-- We will use content_json to store the rich text problem statement.

-- Update Quizzes Table to ensure it supports the JSON structure
ALTER TABLE public.quizzes
ADD COLUMN IF NOT EXISTS grading_rubric jsonb;

-- Create a table for AI generation logs (optional but good for debugging)
CREATE TABLE IF NOT EXISTS public.ai_generation_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
    prompt text,
    response_json jsonb,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

GRANT ALL ON public.ai_generation_logs TO postgres, service_role;
