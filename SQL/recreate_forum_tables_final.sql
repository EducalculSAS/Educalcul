-- Recreate Forum Tables with BIGINT user_id (Corrected)
-- This matches the public.users.id type (BigInt) as used in the PHP admin panel.

-- 1. Drop existing tables to reset structure
DROP TABLE IF EXISTS public.forum_posts;
DROP TABLE IF EXISTS public.forum_topics;

-- 2. Create forum_topics with BIGINT user_id
CREATE TABLE public.forum_topics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    content text NOT NULL,
    category text DEFAULT 'Général',
    -- CHANGE: user_id is bigint to match public.users.id
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    is_pinned boolean DEFAULT false,
    is_locked boolean DEFAULT false,
    views integer DEFAULT 0
);

-- 3. Create forum_posts with BIGINT user_id
CREATE TABLE public.forum_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id bigint REFERENCES public.forum_topics(id) ON DELETE CASCADE,
    content text NOT NULL,
    -- CHANGE: user_id is bigint to match public.users.id
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- 4. Grant permissions
GRANT SELECT, INSERT, UPDATE, DELETE ON public.forum_topics TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.forum_posts TO authenticated;
GRANT SELECT ON public.forum_topics TO anon;
GRANT SELECT ON public.forum_posts TO anon;

