-- Create Quiz related tables

-- Table: quiz_folders
CREATE TABLE IF NOT EXISTS public.quiz_folders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text,
    parent_id bigint REFERENCES public.quiz_folders(id) ON DELETE CASCADE,
    color text DEFAULT '#6c757d',
    icon text,
    display_order integer DEFAULT 0,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: quizzes
CREATE TABLE IF NOT EXISTS public.quizzes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text,
    course_id bigint REFERENCES public.courses(id) ON DELETE SET NULL,
    folder_id bigint REFERENCES public.quiz_folders(id) ON DELETE SET NULL,
    time_limit_minutes integer,
    status text DEFAULT 'draft', -- 'draft', 'published', 'archived'
    thumbnail_filename text,
    content_json jsonb,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: user_quiz_attempts
CREATE TABLE IF NOT EXISTS public.user_quiz_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    quiz_id bigint REFERENCES public.quizzes(id) ON DELETE CASCADE,
    score integer DEFAULT 0,
    total_questions integer DEFAULT 0,
    answers_json jsonb,
    completed_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Enable RLS (Row Level Security) if needed, but for now basic tables are enough.
-- Grant permissions if necessary (usually authenticated and service_role have access by default in Supabase setup, but explicit grants help)
GRANT ALL ON public.quiz_folders TO postgres, service_role;
GRANT ALL ON public.quizzes TO postgres, service_role;
GRANT ALL ON public.user_quiz_attempts TO postgres, service_role;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.quiz_folders TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.quizzes TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.user_quiz_attempts TO authenticated;

GRANT SELECT ON public.quiz_folders TO anon;
GRANT SELECT ON public.quizzes TO anon;
