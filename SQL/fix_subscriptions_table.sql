-- Drop table if exists to rebuild it correctly
DROP TABLE IF EXISTS public.subscriptions CASCADE;

-- Create Subscriptions table with correct types
CREATE TABLE public.subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE, -- Link directly to Auth ID
    plan_id text NOT NULL, -- Store 'premium', 'family' directly as string
    status text DEFAULT 'active',
    current_period_start timestamp with time zone,
    current_period_end timestamp with time zone,
    cancel_at_period_end boolean DEFAULT false,
    stripe_customer_id text,
    stripe_subscription_id text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Enable RLS
ALTER TABLE public.subscriptions ENABLE ROW LEVEL SECURITY;

-- Allow users to view their own subscription
CREATE POLICY "Users can view own subscription"
ON public.subscriptions FOR SELECT
USING (auth.uid() = user_id);

-- Allow Service Role to do everything (for API routes)
CREATE POLICY "Service Role full access"
ON public.subscriptions FOR ALL
TO service_role
USING (true)
WITH CHECK (true);
