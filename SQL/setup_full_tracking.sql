-- Script complet pour le suivi détaillé des utilisateurs (Temps, Scores, IA)

-- 1. Table pour les sessions de connexion globales
CREATE TABLE IF NOT EXISTS public.user_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    auth_session_id UUID, -- Lien avec la session Supabase Auth si dispo
    login_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    last_active_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    logout_at TIMESTAMP WITH TIME ZONE,
    duration_seconds INTEGER DEFAULT 0, -- Calculé à la fin ou maj régulièrement
    ip_address TEXT,
    user_agent TEXT,
    device_type TEXT
);

-- Index pour la recherche rapide de sessions
CREATE INDEX IF NOT EXISTS idx_user_sessions_user_id ON public.user_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_user_sessions_last_active ON public.user_sessions(last_active_at);

-- 2. Table pour le suivi de l'utilisation de l'IA
CREATE TABLE IF NOT EXISTS public.user_ai_interactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    feature_type TEXT NOT NULL, -- 'chatbot', 'hint', 'explanation', 'generation'
    context_id BIGINT, -- ID du cours/exo/quiz lié si applicable
    context_type TEXT, -- 'course', 'exercise', 'quiz'
    prompt_tokens INTEGER DEFAULT 0,
    completion_tokens INTEGER DEFAULT 0,
    duration_seconds INTEGER DEFAULT 0, -- Temps de traitement ou temps de lecture
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ai_interactions_user ON public.user_ai_interactions(user_id);

-- 3. Ajout de colonnes de temps aux tables existantes (si elles n'existent pas)

-- Pour user_course_progress : temps cumulé passé sur le cours
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'user_course_progress' AND column_name = 'time_spent_seconds') THEN
        ALTER TABLE public.user_course_progress ADD COLUMN time_spent_seconds INTEGER DEFAULT 0;
    END IF;
END $$;

-- Pour user_quiz_attempts : durée de la tentative (si pas déjà présent)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'user_quiz_attempts' AND column_name = 'duration_seconds') THEN
        ALTER TABLE public.user_quiz_attempts ADD COLUMN duration_seconds INTEGER DEFAULT 0;
    END IF;
END $$;

-- 4. Vues pour les rapports (Facilite l'affichage dans l'admin)

-- Vue : Statistiques globales par utilisateur
CREATE OR REPLACE VIEW public.view_user_global_stats AS
SELECT 
    u.id,
    u.email,
    u.first_name,
    u.last_name,
    u.role,
    -- Temps total de connexion (somme des sessions)
    COALESCE((SELECT SUM(duration_seconds) FROM public.user_sessions s WHERE s.user_id = u.id), 0) as total_session_time,
    -- Nombre de connexions
    COALESCE((SELECT COUNT(*) FROM public.user_sessions s WHERE s.user_id = u.id), 0) as login_count,
    -- Moyenne Quiz
    COALESCE((SELECT AVG(score) FROM public.user_quiz_attempts q WHERE q.user_id = u.id), 0) as avg_quiz_score,
    -- Moyenne Exos
    COALESCE((SELECT AVG(score) FROM public.user_exercise_attempts e WHERE e.user_id = u.id), 0) as avg_exercise_score,
    -- Temps total Cours
    COALESCE((SELECT SUM(time_spent_seconds) FROM public.user_course_progress c WHERE c.user_id = u.id), 0) as total_learning_time
FROM 
    public.users u;

-- Permissions (RLS)
ALTER TABLE public.user_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_ai_interactions ENABLE ROW LEVEL SECURITY;

-- Politique : Les utilisateurs peuvent voir/créer leurs propres données
CREATE POLICY "Users can insert their own sessions" ON public.user_sessions FOR INSERT WITH CHECK (auth.uid() = (SELECT auth_id FROM public.users WHERE id = user_id));
CREATE POLICY "Users can update their own sessions" ON public.user_sessions FOR UPDATE USING (auth.uid() = (SELECT auth_id FROM public.users WHERE id = user_id));
CREATE POLICY "Users can view their own sessions" ON public.user_sessions FOR SELECT USING (auth.uid() = (SELECT auth_id FROM public.users WHERE id = user_id));

