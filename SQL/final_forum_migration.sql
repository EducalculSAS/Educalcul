-- MIGRATION: Update Forum Schema to Unified Version
-- This script aligns the database with the Next.js Admin Panel and PHP Child Interface.
-- It handles:
-- 1. Creating/Ensuring forum_categories table
-- 2. Recreating forum_topics with BIGINT user_id and category_id FK
-- 3. Recreating forum_posts with BIGINT user_id
-- 4. Setting up correct Foreign Keys and Permissions

BEGIN;

-- 1. Ensure Categories Table Exists
CREATE TABLE IF NOT EXISTS public.forum_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text,
    slug text,
    display_order integer DEFAULT 0,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Seed default categories
INSERT INTO public.forum_categories (name, description, slug, display_order)
SELECT 'Général', 'Discussions générales', 'general', 1
WHERE NOT EXISTS (SELECT 1 FROM public.forum_categories WHERE slug = 'general');

INSERT INTO public.forum_categories (name, description, slug, display_order)
SELECT 'Entraide', 'Aide aux devoirs', 'entraide', 2
WHERE NOT EXISTS (SELECT 1 FROM public.forum_categories WHERE slug = 'entraide');

INSERT INTO public.forum_categories (name, description, slug, display_order)
SELECT 'Annonces', 'Annonces officielles', 'annonces', 0
WHERE NOT EXISTS (SELECT 1 FROM public.forum_categories WHERE slug = 'annonces');

-- 2. Recreate Topics and Posts Tables
-- We DROP them to ensure clean schema. WARNING: This deletes existing topics!
DROP TABLE IF EXISTS public.forum_posts CASCADE;
DROP TABLE IF EXISTS public.forum_topics CASCADE;

CREATE TABLE public.forum_topics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    category_id bigint CONSTRAINT forum_topics_category_id_fkey REFERENCES public.forum_categories(id) ON DELETE SET NULL,
    user_id bigint CONSTRAINT forum_topics_user_id_fkey REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    is_pinned boolean DEFAULT false,
    is_locked boolean DEFAULT false,
    views integer DEFAULT 0,
    -- PHP Compatibility
    last_post_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    last_post_user_id bigint CONSTRAINT forum_topics_last_post_user_id_fkey REFERENCES public.users(id) ON DELETE SET NULL,
    post_count integer DEFAULT 1
);

CREATE TABLE public.forum_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id bigint REFERENCES public.forum_topics(id) ON DELETE CASCADE,
    content text NOT NULL,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- 3. Permissions
GRANT ALL ON public.forum_categories TO authenticated;
GRANT ALL ON public.forum_topics TO authenticated;
GRANT ALL ON public.forum_posts TO authenticated;
GRANT SELECT ON public.forum_categories TO anon;
GRANT SELECT ON public.forum_topics TO anon;
GRANT SELECT ON public.forum_posts TO anon;

-- 4. Reload Schema Cache
NOTIFY pgrst, 'reload schema';

COMMIT;
