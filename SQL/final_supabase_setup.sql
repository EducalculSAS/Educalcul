-- 8. Auth Tokens (Optional, kept for compatibility)
create table public.auth_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id),
  selector text not null,
  hashed_validator text not null,
  expires_at timestamp with time zone not null
);

-- 9. Row Level Security (RLS) & Policies
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- Helper function to avoid infinite recursion in policies
CREATE OR REPLACE FUNCTION get_my_user_id()
RETURNS bigint
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT id FROM public.users WHERE auth_id = auth.uid();
$$;

-- Policy: Users can see their own profile
CREATE POLICY "Users can view their own profile" 
ON public.users FOR SELECT 
USING (auth.uid() = auth_id);

-- Policy: Users can update their own profile
CREATE POLICY "Users can update their own profile" 
ON public.users FOR UPDATE 
USING (auth.uid() = auth_id);

-- Policy: Allow inserting new users during registration (authenticated or anon if public sign-up)
-- Note: 'auth.uid() = auth_id' ensures you can only insert a record linked to YOUR auth account
CREATE POLICY "Enable insert for authentication" 
ON public.users FOR INSERT 
WITH CHECK (auth.uid() = auth_id);

-- Policy: Parents can view their children
-- Uses the helper function to avoid recursion
CREATE POLICY "Parents can view their children" 
ON public.users FOR SELECT 
USING (
  parent_id = get_my_user_id()
);
