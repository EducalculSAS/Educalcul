-- 1. Enable UUID extension
create extension if not exists "uuid-ossp";

-- 2. Users Table (Modified for Supabase Auth)
create table public.users (
  id bigint generated by default as identity primary key,
  auth_id uuid references auth.users(id), -- Link to Supabase Auth
  email text,
  child_username text,
  password_hash text, -- Made nullable as Supabase handles auth
  first_name text,
  last_name text,
  role text not null check (role in ('admin', 'parent', 'child')),
  parent_id bigint references public.users(id),
  grade_level text,
  avatar text default 'default.png',
  custom_title text,
  status text not null default 'pending_verification' check (status in ('pending_verification', 'active', 'inactive', 'banned')),
  email_verification_token text,
  email_verification_expires_at timestamp with time zone,
  email_verified_at timestamp with time zone,
  created_at timestamp with time zone default timezone('utc'::text, now()),
  updated_at timestamp with time zone default timezone('utc'::text, now()),
  name_animation text default 'soft-sparkle',
  avatar_border text default 'border-admin',
  account_type text default 'parent' check (account_type in ('parent', 'child', 'autonomous_child')),
  subscription_plan_id bigint,
  subscription_expires_at timestamp with time zone,
  requires_supervision boolean default false
);

-- 3. Badges Table
create table public.badges (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  icon text not null,
  color text default '#ffd700',
  category text default 'achievement' check (category in ('progression', 'achievement', 'special', 'time_based')),
  requirement_type text not null check (requirement_type in ('quiz_count', 'course_count', 'exercise_count', 'streak_days', 'total_time', 'perfect_scores', 'special')),
  requirement_value integer not null,
  points_reward integer default 10,
  unlocks_avatar_border text,
  unlocks_name_animation text,
  display_order integer default 0,
  is_active boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 4. User Badges Table
create table public.user_badges (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id),
  badge_id bigint not null references public.badges(id),
  unlocked_at timestamp with time zone default timezone('utc'::text, now())
);

-- 5. Billing History Table
create table public.billing_history (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id),
  subscription_id bigint,
  stripe_invoice_id text,
  stripe_payment_intent_id text,
  amount decimal(10,2) not null,
  currency text not null default 'EUR',
  status text not null default 'pending' check (status in ('pending', 'paid', 'failed', 'refunded', 'cancelled')),
  billing_date timestamp with time zone not null,
  paid_at timestamp with time zone,
  description text,
  invoice_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()),
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- 6. Chatbot Conversations Table
create table public.chatbot_conversations (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id),
  user_message text not null,
  bot_response text not null,
  intent text,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 7. AI Analysis Cache Table
create table public.ai_analysis_cache (
  id bigint generated by default as identity primary key,
  child_id bigint not null references public.users(id),
  analysis_text text not null,
  generated_at timestamp with time zone default timezone('utc'::text, now())
