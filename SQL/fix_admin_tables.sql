-- Fix missing admin tables (Settings, Support, Reports, Subscriptions)

-- 1. System Settings
CREATE TABLE IF NOT EXISTS public.system_settings (
    key text PRIMARY KEY,
    value text,
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.system_settings ENABLE ROW LEVEL SECURITY;

-- 2. Support Tickets
CREATE TABLE IF NOT EXISTS public.support_tickets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    user_email text,
    user_name text,
    subject text NOT NULL,
    message text NOT NULL,
    status text DEFAULT 'Ouvert' CHECK (status IN ('Ouvert', 'En cours', 'Répondu', 'Résolu')),
    priority text DEFAULT 'normal' CHECK (priority IN ('normal', 'high')),
    assigned_to uuid REFERENCES auth.users(id),
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    is_archived boolean DEFAULT false,
    archived_at timestamp with time zone
);

CREATE TABLE IF NOT EXISTS public.ticket_replies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id bigint REFERENCES public.support_tickets(id) ON DELETE CASCADE,
    admin_name text,
    reply_message text NOT NULL,
    replied_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- 3. Forum (Basic structure for Reports count)
CREATE TABLE IF NOT EXISTS public.forum_topics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    content text,
    user_id uuid REFERENCES auth.users(id),
    category text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.forum_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id bigint REFERENCES public.forum_topics(id) ON DELETE CASCADE,
    content text NOT NULL,
    user_id uuid REFERENCES auth.users(id),
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- 4. User Quiz Attempts (for Reports stats)
CREATE TABLE IF NOT EXISTS public.user_quiz_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
    quiz_id bigint REFERENCES public.quizzes(id) ON DELETE SET NULL,
    score numeric,
    max_score numeric,
    completed_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- 5. Subscriptions
CREATE TABLE IF NOT EXISTS public.subscription_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text,
    price numeric NOT NULL,
    billing_interval text DEFAULT 'month',
    duration_months integer,
    trial_days integer,
    promo_description text,
    features jsonb DEFAULT '{}',
    is_active boolean DEFAULT true,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
    plan_id bigint REFERENCES public.subscription_plans(id),
    status text DEFAULT 'active',
    current_period_start timestamp with time zone,
    current_period_end timestamp with time zone,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- 6. Permissions
GRANT ALL ON public.system_settings TO authenticated;
GRANT ALL ON public.support_tickets TO authenticated;
GRANT ALL ON public.ticket_replies TO authenticated;
GRANT ALL ON public.forum_topics TO authenticated;
GRANT ALL ON public.forum_posts TO authenticated;
GRANT ALL ON public.user_quiz_attempts TO authenticated;
GRANT ALL ON public.subscription_plans TO authenticated;
GRANT ALL ON public.subscriptions TO authenticated;

