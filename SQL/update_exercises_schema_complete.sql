-- Comprehensive schema update for exercises table
-- Run this script in your Supabase SQL Editor to fix missing columns

-- 1. Create table if it doesn't exist (base structure)
CREATE TABLE IF NOT EXISTS public.exercises (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- 2. Add ALL required columns (idempotent: won't fail if they exist)
ALTER TABLE public.exercises 
ADD COLUMN IF NOT EXISTS title text,
ADD COLUMN IF NOT EXISTS question text, -- Used for description
ADD COLUMN IF NOT EXISTS status text DEFAULT 'draft', -- 'published', 'draft', 'archived'
ADD COLUMN IF NOT EXISTS thumbnail_url text,
ADD COLUMN IF NOT EXISTS course_id bigint REFERENCES public.courses(id) ON DELETE SET NULL,
ADD COLUMN IF NOT EXISTS folder_id bigint REFERENCES public.exercise_folders(id) ON DELETE SET NULL,
ADD COLUMN IF NOT EXISTS max_attempts integer DEFAULT NULL,
ADD COLUMN IF NOT EXISTS time_limit integer DEFAULT NULL,
ADD COLUMN IF NOT EXISTS difficulty_level text DEFAULT 'medium',
ADD COLUMN IF NOT EXISTS type text DEFAULT 'standard',
ADD COLUMN IF NOT EXISTS grading_type text DEFAULT 'auto',
ADD COLUMN IF NOT EXISTS content_json jsonb DEFAULT '[]'::jsonb,
ADD COLUMN IF NOT EXISTS ai_generated boolean DEFAULT false,
ADD COLUMN IF NOT EXISTS grading_rubric jsonb,
ADD COLUMN IF NOT EXISTS solution_text text,
ADD COLUMN IF NOT EXISTS user_prompt text;

-- 3. Notify PostgREST to refresh the schema cache immediately
NOTIFY pgrst, 'reload schema';
