-- Fix inconsistencies in public.users
BEGIN;

UPDATE public.users SET account_type = 'child' WHERE role = 'child';
UPDATE public.users SET account_type = 'parent' WHERE role = 'parent';
UPDATE public.users SET child_age = NULL WHERE role = 'parent';

-- Create Tables from Educalcul (Legacy)

-- Table: badges
CREATE TABLE IF NOT EXISTS public.badges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text,
    icon text NOT NULL,
    color text DEFAULT '#ffd700',
    category text DEFAULT 'achievement',
    requirement_type text NOT NULL,
    requirement_value integer NOT NULL,
    points_reward integer DEFAULT 10,
    unlocks_avatar_border text,
    unlocks_name_animation text,
    display_order integer DEFAULT 0,
    is_active boolean DEFAULT true,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: subscription_plans
CREATE TABLE IF NOT EXISTS public.subscription_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    stripe_price_id text,
    price_monthly numeric(10,2),
    price_yearly numeric(10,2),
    features jsonb,
    is_active boolean DEFAULT true
);

-- Table: subscriptions
CREATE TABLE IF NOT EXISTS public.subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    plan_id bigint REFERENCES public.subscription_plans(id),
    stripe_subscription_id text,
    stripe_customer_id text,
    status text DEFAULT 'active',
    current_period_start timestamp with time zone,
    current_period_end timestamp with time zone,
    cancel_at_period_end boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: billing_history
CREATE TABLE IF NOT EXISTS public.billing_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    subscription_id bigint REFERENCES public.subscriptions(id) ON DELETE SET NULL,
    stripe_invoice_id text,
    amount numeric(10,2),
    currency text DEFAULT 'eur',
    status text,
    billing_date timestamp with time zone,
    invoice_pdf_url text
);

-- Table: course_folders
CREATE TABLE IF NOT EXISTS public.course_folders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text,
    parent_id bigint REFERENCES public.course_folders(id) ON DELETE CASCADE,
    grade_level text,
    subject text,
    icon text,
    color text,
    display_order integer DEFAULT 0,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    is_public boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: courses
CREATE TABLE IF NOT EXISTS public.courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    slug text,
    description text,
    content text,
    grade_level text,
    subject text,
    folder_id bigint REFERENCES public.course_folders(id) ON DELETE SET NULL,
    thumbnail_url text,
    video_url text,
    estimated_duration integer, -- in minutes
    difficulty_level text DEFAULT 'medium',
    points_reward integer DEFAULT 0,
    is_published boolean DEFAULT false,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: exercise_folders
CREATE TABLE IF NOT EXISTS public.exercise_folders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text,
    parent_id bigint REFERENCES public.exercise_folders(id) ON DELETE CASCADE,
    grade_level text,
    subject text,
    icon text,
    color text,
    display_order integer DEFAULT 0,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    is_public boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: exercises
CREATE TABLE IF NOT EXISTS public.exercises (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    slug text,
    description text,
    instruction text,
    content jsonb, -- structured content for the exercise
    solution jsonb,
    type text NOT NULL, -- e.g., 'multiple_choice', 'fill_gap', 'drag_drop'
    grade_level text,
    subject text,
    folder_id bigint REFERENCES public.exercise_folders(id) ON DELETE SET NULL,
    difficulty_level text DEFAULT 'medium',
    points_reward integer DEFAULT 10,
    thumbnail_url text,
    is_published boolean DEFAULT false,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: user_course_progress
CREATE TABLE IF NOT EXISTS public.user_course_progress (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    course_id bigint REFERENCES public.courses(id) ON DELETE CASCADE,
    status text DEFAULT 'not_started', -- 'not_started', 'in_progress', 'completed'
    progress_percentage integer DEFAULT 0,
    last_accessed_at timestamp with time zone,
    completed_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    UNIQUE(user_id, course_id)
);

-- Table: user_exercise_attempts
CREATE TABLE IF NOT EXISTS public.user_exercise_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    exercise_id bigint REFERENCES public.exercises(id) ON DELETE CASCADE,
    score integer,
    max_score integer,
    is_correct boolean,
    duration_seconds integer,
    attempt_data jsonb, -- detailed answers
    attempted_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: parent_child_links
CREATE TABLE IF NOT EXISTS public.parent_child_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    child_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    UNIQUE(parent_id, child_id)
);

-- Table: user_badges
CREATE TABLE IF NOT EXISTS public.user_badges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    badge_id bigint REFERENCES public.badges(id) ON DELETE CASCADE,
    earned_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    UNIQUE(user_id, badge_id)
);

-- Table: conversations
CREATE TABLE IF NOT EXISTS public.conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text DEFAULT 'direct', -- 'direct', 'group', 'support'
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

-- Table: conversation_participants (New table to handle many-to-many, better than just user_id in conversation)
CREATE TABLE IF NOT EXISTS public.conversation_participants (
    conversation_id bigint REFERENCES public.conversations(id) ON DELETE CASCADE,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    joined_at timestamp with time zone DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (conversation_id, user_id)
);

-- Table: messages
CREATE TABLE IF NOT EXISTS public.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint REFERENCES public.conversations(id) ON DELETE CASCADE,
    sender_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
    content text,
    is_read boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now())
);

COMMIT;
